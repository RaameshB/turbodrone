#!/usr/bin/env python3
"""
Calibrate the drone camera from frames recorded with record_frames.py while
a printed checkerboard is moved in front of the lens, and write the stella_vslam
monocular config (default: slam/config/drone.yaml).

    python3 slam/calibrate.py recordings/calib --cols 9 --rows 6 [--fps 25]

--cols/--rows are INNER corner counts (squares - 1). Square size does not
matter for intrinsics. Needs OpenCV (run inside the `ros2` distrobox).
"""
import argparse
import glob
import os
import sys

import cv2
import numpy as np

TEMPLATE = """# Generated by slam/calibrate.py (RMS reprojection error {rms:.3f} px, {n} views)
Camera:
  name: "turbodrone"
  setup: "monocular"
  model: "perspective"
  fx: {fx:.6f}
  fy: {fy:.6f}
  cx: {cx:.6f}
  cy: {cy:.6f}
  k1: {k1:.6f}
  k2: {k2:.6f}
  p1: {p1:.6f}
  p2: {p2:.6f}
  k3: {k3:.6f}
  fps: {fps:.1f}
  cols: {cols}
  rows: {rows}
  color_order: "Gray"

Preprocessing:
  min_size: 150

Feature:
  name: "default ORB feature extraction setting"
  scale_factor: 1.2
  num_levels: 6
  ini_fast_threshold: 15
  min_fast_threshold: 5

Tracking:
  init_retry_threshold_time: 0.0

Initializer:
  min_num_valid_pts: 25
  min_num_triangulated_pts: 25
  parallax_deg_threshold: 0.5

Relocalizer:
  bow_match_lowe_ratio: 0.85
  proj_match_lowe_ratio: 0.95
  min_num_bow_matches: 10
  min_num_valid_obs: 15
  num_common_words_thr_ratio: 0.5
  max_num_ransac_iter: 50

Mapping:
  baseline_dist_thr_ratio: 0.02
  redundant_obs_ratio_thr: 0.9
  num_covisibilities_for_landmark_generation: 20
  num_covisibilities_for_landmark_fusion: 20
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("framedir")
    ap.add_argument("--cols", type=int, required=True)
    ap.add_argument("--rows", type=int, required=True)
    ap.add_argument("--fps", type=float, default=25.0)
    ap.add_argument("--every", type=int, default=5, help="use every Nth frame")
    ap.add_argument("--min-shift", type=float, default=12.0, help="min mean corner displacement (px) from all kept views")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "config", "drone.yaml"))
    a = ap.parse_args()

    files = sorted(glob.glob(os.path.join(a.framedir, "*.jpg")))[:: a.every]
    pattern = (a.cols, a.rows)
    objp = np.zeros((a.cols * a.rows, 3), np.float32)
    objp[:, :2] = np.mgrid[0:a.cols, 0:a.rows].T.reshape(-1, 2)
    objpts, imgpts, size = [], [], None
    crit = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 30, 0.001)
    for f in files:
        g = cv2.imread(f, cv2.IMREAD_GRAYSCALE)
        if g is None:
            continue
        size = g.shape[::-1]
        ok, c = cv2.findChessboardCorners(g, pattern, cv2.CALIB_CB_ADAPTIVE_THRESH | cv2.CALIB_CB_NORMALIZE_IMAGE)
        if ok:
            win = (5, 5) if min(size) <= 320 else (11, 11)
            sub = cv2.cornerSubPix(g, c, win, (-1, -1), crit)
            if any(float(np.linalg.norm(sub - prev, axis=-1).mean()) < a.min_shift for prev in imgpts):
                continue
            imgpts.append(sub)
            objpts.append(objp)
    if len(objpts) < 15:
        print(f"only {len(objpts)} distinct views of {len(files)} frames; need >= 15 with varied tilt/position", file=sys.stderr)
        return 1
    flags = cv2.CALIB_FIX_K3
    rms, K, D, rvecs, tvecs = cv2.calibrateCamera(objpts, imgpts, size, None, None, flags=flags)
    errs = [
        float(np.sqrt(np.mean(np.sum((imgpts[i].reshape(-1, 2) - cv2.projectPoints(objpts[i], rvecs[i], tvecs[i], K, D)[0].reshape(-1, 2)) ** 2, axis=-1))))
        for i in range(len(objpts))
    ]
    thr = max(0.5, 1.5 * float(np.median(errs)))
    keep = [i for i, e in enumerate(errs) if e <= thr]
    if len(keep) >= 15 and len(keep) < len(objpts):
        objpts = [objpts[i] for i in keep]
        imgpts = [imgpts[i] for i in keep]
        rms, K, D, _, _ = cv2.calibrateCamera(objpts, imgpts, size, None, None, flags=flags)
    d = list(D.ravel()) + [0.0] * 5
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write(TEMPLATE.format(rms=rms, n=len(objpts), fx=K[0, 0], fy=K[1, 1], cx=K[0, 2], cy=K[1, 2],
                                 k1=d[0], k2=d[1], p1=d[2], p2=d[3], k3=d[4], fps=a.fps, cols=size[0], rows=size[1]))
    print(f"RMS {rms:.3f}px from {len(objpts)} views, {size[0]}x{size[1]} -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
